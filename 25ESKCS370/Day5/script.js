/* ================= INIT ================= */
$(document).ready(function () {

  renderStudents(students);
  loadDepartments();
  updateStats();

  /* ================= SEARCH BUTTON (NAME + ID ONLY) ================= */
  $("#searchBtn").on("click", function () {
    searchByNameId();
  });

  /* ================= DEPARTMENT FILTER ================= */
  $("#departmentFilter").on("change", function () {
    filterByDepartment();
  });

  /* ================= CGPA FILTER ================= */
  $("#cgpaFilter").on("change", function () {
    filterByCgpa();
  });

  /* ================= MODAL OPEN ================= */
  $(document).on("click", ".view-details", function () {
    let id = $(this).data("id");
    openModal(id);
  });

  /* ESC CLOSE MODAL */
  $(document).on("keydown", function (e) {
    if (e.key === "Escape") {
      $("#studentModal").modal("hide");
    }
  });

});

/* ================= SEARCH ONLY (NAME + ID) ================= */
function searchByNameId() {

  let query = $("#searchBox").val().toLowerCase().trim();

  currentList = students.filter(s =>
    s.name.toLowerCase().includes(query) ||
    s.id.toLowerCase().includes(query)
  );

  renderStudents(currentList);
}

/* ================= DEPARTMENT FILTER (INDEPENDENT) ================= */
function filterByDepartment() {

  let dept = $("#departmentFilter").val();

  currentList = students.filter(s => {
    return dept === "" || s.department === dept;
  });

  renderStudents(currentList);
}

/* ================= CGPA FILTER (INDEPENDENT) ================= */
function filterByCgpa() {

  let cgpa = $("#cgpaFilter").val();

  currentList = students.filter(s => {

    if (cgpa === "") return true;

    return s.cgpa >= parseFloat(cgpa);
  });

  renderStudents(currentList);
}

/* ================= RENDER STUDENTS ================= */
function renderStudents(list) {

  let container = $("#studentContainer");
  container.empty();

  if (list.length === 0) {
    container.html(`
      <div class="text-center w-100 mt-5">
        <h4>No Students Found</h4>
      </div>
    `);
    return;
  }

  list.forEach(s => {

    container.append(`
      <div class="col-md-4">

        <div class="student-card">

          <div class="d-flex align-items-center gap-3">
            <img src="${s.photo}" class="student-img">

            <div>
              <div class="student-name">${s.name}</div>
              <div class="student-info">ID: ${s.id}</div>
              <div class="student-info">Roll: ${s.roll}</div>
            </div>
          </div>

          <hr>

          <div class="student-info"><b>Dept:</b> ${s.department}</div>
          <div class="student-info"><b>CGPA:</b> ${s.cgpa}</div>
          <div class="student-info"><b>Attendance:</b> ${s.attendance}%</div>

          <div class="mt-2">
            <span class="status ${s.status}">
              ${s.status.toUpperCase()}
            </span>
          </div>

          <button class="btn btn-info w-100 mt-3 view-details"
            data-id="${s.id}">
            More Details
          </button>

        </div>

      </div>
    `);
  });
}

/* ================= LOAD DEPARTMENTS ================= */
function loadDepartments() {

  let depts = [...new Set(students.map(s => s.department))];

  depts.forEach(d => {
    $("#departmentFilter").append(`
      <option value="${d}">${d}</option>
    `);
  });
}

/* ================= STATS ================= */
function updateStats() {

  $("#totalStudents").text(students.length);

  let active = students.filter(s => s.status === "active").length;
  $("#activeStudents").text(active);

  let avgCgpa = (students.reduce((a, b) => a + b.cgpa, 0) / students.length).toFixed(2);
  $("#avgCgpa").text(avgCgpa);

  let avgAtt = (students.reduce((a, b) => a + b.attendance, 0) / students.length).toFixed(1);
  $("#avgAttendance").text(avgAtt + "%");
}

/* ================= MODAL ================= */
function openModal(id) {

  let s = students.find(stu => stu.id === id);

  $("#modalBody").html(`
    <div class="text-center mb-3">
      <img src="${s.photo}" class="rounded-circle border border-3 border-info" width="110">
      <h4 class="text-info">${s.name}</h4>
      <small>${s.department}</small>
    </div>

    <div class="row">
      <div class="col-md-6">
        <p><b>ID:</b> ${s.id}</p>
        <p><b>Roll:</b> ${s.roll}</p>
        <p><b>Department:</b> ${s.department}</p>
      </div>

      <div class="col-md-6">
        <p><b>CGPA:</b> ${s.cgpa}</p>
        <p><b>Attendance:</b> ${s.attendance}%</p>
        <p><b>Email:</b> ${s.email}</p>
        <p><b>Phone:</b> ${s.phone}</p>
      </div>
    </div>
  `);

  $("#studentModal").modal("show");
}